"""Regenerate a tiny two-function stateful model with coremltools 9."""
import pathlib
import tempfile

import coremltools as ct
from coremltools.converters.mil import Builder as mb
from coremltools.converters.mil.mil import types


@mb.program(
    input_specs=[mb.TensorSpec((1,), dtype=types.fp16),
                 mb.StateTensorSpec((1,), dtype=types.fp16)],
    opset_version=ct.target.iOS18,
)
def accumulator(x, accumulator):
    y = mb.add(x=x, y=mb.read_state(input=accumulator), name="y")
    mb.coreml_update_state(state=accumulator, value=y)
    return y


@mb.program(
    input_specs=[mb.TensorSpec((2,), dtype=types.fp16),
                 mb.StateTensorSpec((2,), dtype=types.fp16)],
    opset_version=ct.target.iOS18,
)
def different_state(x, accumulator):
    y = mb.add(x=x, y=mb.read_state(input=accumulator), name="y")
    mb.coreml_update_state(state=accumulator, value=y)
    return y


with tempfile.TemporaryDirectory() as temporary:
    root = pathlib.Path(temporary)
    source = root / "accumulator.mlpackage"
    target = root / "functions.mlpackage"
    model = ct.convert(accumulator, minimum_deployment_target=ct.target.iOS18, skip_model_load=True)
    model.save(str(source))
    different = root / "different.mlpackage"
    ct.convert(different_state, minimum_deployment_target=ct.target.iOS18,
               skip_model_load=True).save(str(different))
    descriptor = ct.utils.MultiFunctionDescriptor()
    descriptor.add_function(str(source), "main", "decode")
    descriptor.add_function(str(source), "main", "prefill")
    descriptor.add_function(str(different), "main", "different")
    descriptor.default_function_name = "decode"
    ct.utils.save_multifunction(descriptor, str(target))
    spec = ct.utils.load_spec(str(target))
    spec.description.metadata.userDefined.pop("com.github.apple.coremltools.conversion_date", None)
    data = spec.SerializeToString(deterministic=True)

lines = ["    " + ", ".join(map(str, data[i:i + 20])) + "," for i in range(0, len(data), 20)]
pathlib.Path("tests/fixtures/multifunction.rs").write_text(
    "//! Stateful functions with matching and mismatched schemas, generated by coremltools 9.\n"
    "//! Generated from scripts/generate-multifunction-fixture.py; no weights.\n"
    "pub const MODEL: &[u8] = &[\n" + "\n".join(lines) + "\n];\n"
)
